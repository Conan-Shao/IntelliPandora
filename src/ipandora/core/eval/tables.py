"""
@Author: Shao Feng
@File  : tables.py
@Time  : 2026-11-07

The tables of an evaluation report, from the raw results alone: every
number is regenerated by a script from the JSON lines `ipandora eval
records` wrote (E9), never typed in.

    ipandora eval table results/*.jsonl -o results/tables.md

One row per configuration in each table:

- main: tasks, runs, success rate (each task's rate, averaged over tasks),
  its 95% interval (tasks and their runs resampled), pass@k and pass^k;
- green-washing (test-generation runs): how often a run changed files
  other than tests (out of scope), wrote a test that asserts nothing, only
  failed by being broken (weak reproduction), and the mutation score of the
  tests that reached F→P;
- cost per run: tokens (cache reads and writes apart), money, time, turns,
  tool calls -- and money in all;
- why runs failed (testgen.failure_reason), counted;
- every pair of configurations, compared on the tasks both ran.

A run whose infrastructure failed has no verdict: it is left out of the
rates and counted apart, as everywhere else.
"""
import json
from typing import Any, Dict, Iterable, List, Optional

from ipandora.core.eval import stats, testgen

COSTS = ('tokens_in', 'tokens_out', 'tokens_cache_read', 'tokens_cache_write', 'usd', 'seconds', 'turns',
         'tool_calls')


def read(paths: Iterable[str]) -> List[Dict[str, Any]]:
    """Every record of the JSONL files, in order. A line that is not a record names its file and line."""
    paths = list(paths)
    _out = []
    for _path in paths:
        with open(_path, encoding='utf-8') as fh:
            for _n, _line in enumerate(fh, 1):
                if not _line.strip():
                    continue
                try:
                    _row = json.loads(_line)
                except ValueError as exc:
                    raise ValueError('{}:{}: not a JSON line: {}'.format(_path, _n, exc))
                if not isinstance(_row, dict) or 'task' not in _row or 'config' not in _row:
                    raise ValueError('{}:{}: not a record of `ipandora eval records` (task, config)'.format(_path, _n))
                _out.append(_row)
    if not _out:
        raise ValueError('no records in {}'.format(', '.join(paths)))
    # the same file twice, or a merged file beside its parts, counted every run twice (CR17)
    _seen, _twice = set(), []
    for _r in _out:
        if not _r.get('run_id'):
            continue
        _key = (_r['config'], _r['task'], _r['run_id'], _r.get('attempt'))
        if _key in _seen:
            _twice.append('{} {} run {} attempt {}'.format(*_key))
        _seen.add(_key)
    if _twice:
        raise ValueError('{} record(s) appear more than once -- the same results read twice? {}'.format(
            len(_twice), '; '.join(_twice[:3])))
    return _out


def configs(rows: List[Dict[str, Any]]) -> List[str]:
    """The configurations, in the order they first appear."""
    _seen = []
    for _r in rows:
        if _r['config'] not in _seen:
            _seen.append(_r['config'])
    return _seen


def outcomes(rows: List[Dict[str, Any]], config: str) -> Dict[str, List[float]]:
    """task -> 1/0 of each decided run of `config`."""
    _out: Dict[str, List[float]] = {}
    for _r in rows:
        if _r['config'] == config and isinstance(_r.get('success'), bool):
            _out.setdefault(_r['task'], []).append(1.0 if _r['success'] else 0.0)
    return _out


def _rate(hits: int, of: int) -> Optional[float]:
    return hits / of if of else None


def main(rows: List[Dict[str, Any]], k: Optional[int] = None) -> List[Dict[str, Any]]:
    """
    :param k: for pass@k and pass^k; default the fewest decided runs of any
              task of that configuration, so every task counts. A task with
              fewer runs than k is left out of both, and counted.
    """
    _out = []
    for _c in configs(rows):
        _mine = [_r for _r in rows if _r['config'] == _c]
        _by = outcomes(rows, _c)
        _rate_, _lo, _hi = stats.task_mean(_by)
        _k = k or (min(len(_v) for _v in _by.values()) if _by else None)
        _at = [stats.pass_at_k(len(_v), int(sum(_v)), _k) for _v in _by.values()] if _k else []
        _hat = [stats.pass_hat_k(len(_v), int(sum(_v)), _k) for _v in _by.values()] if _k else []
        _infra = sum(1 for _r in _mine if not isinstance(_r.get('success'), bool))
        _models = sorted({str(_r.get('model') or '') for _r in _mine} - {''})
        _out.append({'config': _c, 'model': ', '.join(_models), 'tasks': len(_by), 'runs': len(_mine),
                     'decided': sum(len(_v) for _v in _by.values()), 'success_rate': _rate_,
                     'low': _lo, 'high': _hi, 'k': _k,
                     'pass_at_k': _mean([_x for _x in _at if _x is not None]),
                     'pass_hat_k': _mean([_x for _x in _hat if _x is not None]),
                     'short_of_k': sum(1 for _x in _at if _x is None),
                     'no_verdict': _infra,
                     'infra_retries': sum(int(_r.get('infra_retries') or 0) for _r in _mine)})
    return _out


def _mean(values: List[float]) -> Optional[float]:
    return sum(values) / len(values) if values else None


def _failed(row: Dict[str, Any], claim: str) -> bool:
    return any(_c.get('claim') == claim and _c.get('ok') is False for _c in row.get('checks') or [])


def greenwash(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Over the graded test-generation runs of each configuration (those with a
    'fail to pass' check): the out-of-scope, zero-assertion and weak
    reproduction rates, and the mean mutation score of the runs whose tests
    reached F→P and were mutated.
    """
    _out = []
    for _c in configs(rows):
        _graded = [_r for _r in rows if _r['config'] == _c and isinstance(_r.get('success'), bool)
                   and any(_x.get('claim') == 'fail to pass' for _x in _r.get('checks') or [])]
        if not _graded:
            continue
        _scores = [_r['mutation']['killed'] / _r['mutation']['tested'] for _r in _graded
                   if isinstance(_r.get('mutation'), dict) and _r['mutation'].get('tested')]
        # zero assertions among the runs that wrote tests: one that wrote none is no_tests (CR17)
        _wrote = [_r for _r in _graded if not _failed(_r, 'agent wrote tests')]
        _out.append({'config': _c, 'runs': len(_graded), 'wrote_tests': len(_wrote),
                     'out_of_scope': _rate(sum(_failed(_r, 'only test files changed') for _r in _graded), len(_graded)),
                     'zero_assertion': _rate(sum(_failed(_r, 'tests assert') for _r in _wrote), len(_wrote)),
                     'weak_reproduction': _rate(sum(_failed(_r, 'not a weak reproduction') for _r in _graded),
                                                len(_graded)),
                     'mutation_score': _mean(_scores), 'mutated_runs': len(_scores)})
    return _out


def cost(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Each cost key's mean over the runs of a configuration that reported it, and money in all."""
    _out = []
    for _c in configs(rows):
        _mine = [_r for _r in rows if _r['config'] == _c]
        _row = {'config': _c, 'runs': len(_mine)}
        for _k in COSTS:
            _row[_k] = _mean([float(_r[_k]) for _r in _mine
                              if isinstance(_r.get(_k), (int, float)) and not isinstance(_r.get(_k), bool)])
        _usd = [float(_r['usd']) for _r in _mine if isinstance(_r.get('usd'), (int, float))
                and not isinstance(_r.get('usd'), bool)]
        _row['usd_total'] = sum(_usd) if _usd else None
        _row['over_budget'] = sum(1 for _r in _mine if _r.get('over_budget'))
        _out.append(_row)
    return _out


def reasons(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Per configuration: how many runs failed for each reason (testgen.REASONS), and how many succeeded."""
    _out = []
    for _c in configs(rows):
        _mine = [_r for _r in rows if _r['config'] == _c and 'reason' in _r]
        if not _mine:
            continue
        _row: Dict[str, Any] = {'config': _c, 'runs': len(_mine),
                                'succeeded': sum(1 for _r in _mine if not _r['reason'])}
        for _reason in testgen.REASONS:
            _row[_reason] = sum(1 for _r in _mine if _r['reason'] == _reason)
        _out.append(_row)
    return _out


def comparisons(rows: List[Dict[str, Any]], seed: int = 0) -> List[Dict[str, Any]]:
    """Every pair of configurations on the tasks both decided (stats.pairwise: paired, Bonferroni-corrected)."""
    _names = configs(rows)
    if len(_names) < 2:
        return []
    return stats.pairwise({_c: outcomes(rows, _c) for _c in _names}, seed=seed)


def tables(rows: List[Dict[str, Any]], k: Optional[int] = None) -> Dict[str, Any]:
    return {'main': main(rows, k), 'greenwash': greenwash(rows), 'cost': cost(rows), 'reasons': reasons(rows),
            'comparisons': comparisons(rows)}


# -- markdown ---------------------------------------------------------------------------------------

def _pct(value) -> str:
    return '—' if value is None else '{:.1f}%'.format(100 * value)


def _num(value, digits=1) -> str:
    return '—' if value is None else '{:,.{d}f}'.format(value, d=digits)


def _cell(text: str) -> str:
    # a configuration named 'a|b' must not add a column (CR17)
    return str(text).replace('|', '\\|').replace('\n', ' ')


def _table(head: List[str], body: List[List[str]]) -> str:
    return '\n'.join(['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
                     + ['| ' + ' | '.join(_cell(_x) for _x in _r) + ' |' for _r in body])


def markdown(result: Dict[str, Any]) -> str:
    _parts = ['## 主表\n', _table(
        ['配置', '模型', '题', '运行', '成功率', '95% 区间', 'k', 'pass@k', 'pass^k', '没有结论'],
        [[_r['config'], _r['model'] or '—', str(_r['tasks']), str(_r['runs']), _pct(_r['success_rate']),
          '{} – {}'.format(_pct(_r['low']), _pct(_r['high'])), str(_r['k'] or '—'), _pct(_r['pass_at_k']),
          _pct(_r['pass_hat_k']), str(_r['no_verdict'])] for _r in result['main']])]
    _parts.append('\n成功率先算每题的成功比例再对题取平均；区间按题重采样（题和每题的运行都重新抽样）。'
                  '基础设施出错、没有结论的运行不计入成功率。')
    if any(_r['short_of_k'] for _r in result['main']):
        _parts.append('运行次数少于 k 的题不计入 pass@k、pass^k：' + '，'.join(
            '{} {} 道'.format(_r['config'], _r['short_of_k']) for _r in result['main'] if _r['short_of_k']) + '。')
    if result['greenwash']:
        _parts += ['\n## 刷绿指标\n', _table(
            ['配置', '判分的运行', '越界', '零断言', '弱复现', '变异分数', '做了变异的运行'],
            [[_r['config'], str(_r['runs']), _pct(_r['out_of_scope']), _pct(_r['zero_assertion']),
              _pct(_r['weak_reproduction']), _pct(_r['mutation_score']), str(_r['mutated_runs'])]
             for _r in result['greenwash']])]
        _parts.append('\n越界、弱复现以判了分的运行为分母；零断言只算写了测试的运行；变异分数只算达到 F→P、并且做了变异的运行。')
    _parts += ['\n## 成本（每次运行的平均）\n', _table(
        ['配置', '运行', '输入 token', '输出 token', '缓存读', '缓存写', '费用（美元）', '耗时（秒）', '轮数', '工具调用',
         '总费用', '超预算'],
        [[_r['config'], str(_r['runs']), _num(_r['tokens_in'], 0), _num(_r['tokens_out'], 0),
          _num(_r['tokens_cache_read'], 0), _num(_r['tokens_cache_write'], 0), _num(_r['usd'], 4),
          _num(_r['seconds']), _num(_r['turns']), _num(_r['tool_calls']), _num(_r['usd_total'], 2),
          str(_r['over_budget'])] for _r in result['cost']])]
    if result['reasons']:
        _keys = [_k for _k in testgen.REASONS if any(_r[_k] for _r in result['reasons'])]
        _parts += ['\n## 失败原因\n', _table(
            ['配置', '运行', '成功'] + [testgen.REASONS[_k] for _k in _keys],
            [[_r['config'], str(_r['runs']), str(_r['succeeded'])] + [str(_r[_k]) for _k in _keys]
             for _r in result['reasons']])]
    if result['comparisons']:
        _words = {stats.BETTER: '{b} 更好', stats.WORSE: '{b} 更差', stats.INDISTINGUISHABLE: '没有可靠差异'}
        _parts += ['\n## 配置之间\n', _table(
            ['比较', '共同的题', '差（b − a）', '区间', '结论'],
            [['{} → {}'.format(_c['a'], _c['b']), str(_c['tasks']), '{:+.1f} 个点'.format(100 * _c['difference']),
              '{:+.1f} – {:+.1f}（{:.1f}%）'.format(100 * _c['low'], 100 * _c['high'], 100 * _c['level']),
              _words[_c['verdict']].format(a=_c['a'], b=_c['b'])] for _c in result['comparisons']])]
        _parts.append('\n同一批题配对比较，区间按比较的组数做 Bonferroni 校正；区间跨 0 就是没有可靠差异，不排名次。')
    return '\n'.join(_parts) + '\n'


__all__ = ['read', 'tables', 'markdown', 'main', 'greenwash', 'cost', 'reasons', 'comparisons', 'outcomes', 'COSTS']
