import json
import subprocess
import sys

import pytest

from ipandora.core.assertion.check import Check
from ipandora.core.eval import Dataset, evaluate, records, stats, tables
from ipandora.core.eval.dataset import Task


def tg(config, task, ok, attempt=1, out_of_scope=False, asserts=True, weak=False, mutation=None, reason=None,
       **cost):
    """One test-generation record, as `eval records` writes it."""
    _checks = [{'claim': 'fail to pass', 'ok': ok}, {'claim': 'only test files changed', 'ok': not out_of_scope},
               {'claim': 'not a weak reproduction', 'ok': not weak}, {'claim': 'tests assert', 'ok': asserts}]
    _row = {'task': task, 'config': config, 'model': 'm-' + config, 'attempt': attempt, 'success': ok,
            'status': 'graded', 'checks': _checks, 'reason': '' if ok else (reason or 'not_reproduced'),
            'mutation': mutation, 'over_budget': False, 'infra_retries': 0}
    _row.update(cost)
    return _row


def infra(config, task, retries=2):
    return {'task': task, 'config': config, 'model': 'm-' + config, 'attempt': 1, 'success': None,
            'status': 'infra', 'checks': [], 'reason': 'environment', 'infra_retries': retries}


ROWS = [tg('A', 't1', True, usd=0.1, tokens_in=1000, mutation={'killed': 3, 'tested': 4}),
        tg('A', 't1', True, attempt=2, usd=0.3, tokens_in=3000, mutation={'killed': 1, 'tested': 2}),
        tg('A', 't2', False, out_of_scope=True, reason='modified_source', usd=0.2),
        tg('A', 't2', False, attempt=2, weak=True, asserts=False, reason='weak_reproduction'),
        infra('A', 't3'),
        tg('B', 't1', False), tg('B', 't1', False, attempt=2), tg('B', 't2', True), tg('B', 't2', True, attempt=2)]


class TestTheNumbers:

    def test_main(self):
        _a, _b = tables.main(ROWS)
        assert (_a['config'], _a['model'], _a['tasks'], _a['runs'], _a['decided'], _a['no_verdict']) == (
            'A', 'm-A', 2, 5, 4, 1)
        assert _a['success_rate'] == 0.5 and _a['k'] == 2 and _a['infra_retries'] == 2
        assert (_a['pass_at_k'], _a['pass_hat_k']) == (0.5, 0.5)
        assert _a['low'] <= 0.5 <= _a['high']
        assert _b['success_rate'] == 0.5

    def test_k_given_and_tasks_short_of_it(self):
        _rows = ROWS + [tg('A', 't1', False, attempt=3)]
        _a = tables.main(_rows, k=3)[0]
        # t1 has 3 runs (2 of 3), t2 only 2: left out of pass@3 and counted
        assert _a['k'] == 3 and _a['short_of_k'] == 1 and _a['pass_hat_k'] == 0.0 and _a['pass_at_k'] == 1.0
        assert tables.main(_rows)[0]['k'] == 2

    def test_greenwash(self):
        _a, _b = tables.greenwash(ROWS)
        assert (_a['runs'], _a['out_of_scope'], _a['zero_assertion'], _a['weak_reproduction']) == (4, 0.25, 0.25, 0.25)
        assert _a['mutation_score'] == (0.75 + 0.5) / 2 and _a['mutated_runs'] == 2
        assert (_b['out_of_scope'], _b['mutation_score'], _b['mutated_runs']) == (0.0, None, 0)

    def test_greenwash_is_only_for_test_generation(self):
        _plain = [{'task': 't', 'config': 'C', 'success': True, 'checks': [{'claim': 'right', 'ok': True}]}]
        assert tables.greenwash(_plain) == [] and tables.reasons(_plain) == []

    def test_cost(self):
        _a = tables.cost(ROWS)[0]
        # the mean over the runs that reported it: three reported usd, two tokens_in, none turns
        assert (_a['runs'], _a['tokens_in'], _a['turns'], _a['over_budget']) == (5, 2000.0, None, 0)
        assert _a['usd'] == pytest.approx(0.2) and _a['usd_total'] == pytest.approx(0.6)

    def test_reasons(self):
        _a, _b = tables.reasons(ROWS)
        assert (_a['runs'], _a['succeeded'], _a['modified_source'], _a['weak_reproduction'], _a['environment']) == (
            5, 2, 1, 1, 1)
        assert (_b['succeeded'], _b['not_reproduced']) == (2, 2)

    def test_comparisons_are_paired_on_shared_tasks(self):
        _c = tables.comparisons(ROWS)
        assert len(_c) == 1 and (_c[0]['a'], _c[0]['b'], _c[0]['tasks']) == ('A', 'B', 2)
        assert _c[0]['verdict'] == stats.INDISTINGUISHABLE
        assert tables.comparisons([_r for _r in ROWS if _r['config'] == 'A']) == []

    def test_the_markdown(self):
        _md = tables.markdown(tables.tables(ROWS))
        assert '## 主表' in _md and '| A | m-A | 2 | 5 | 50.0% |' in _md
        assert '## 刷绿指标' in _md and '| A | 4 | 25.0% | 25.0% | 25.0% | 62.5% | 2 |' in _md
        assert '## 失败原因' in _md and '改了源码' in _md and '弱复现' in _md
        assert '## 配置之间' in _md and 'A → B' in _md and '没有可靠差异' in _md
        assert '超时或超预算' not in _md            # a reason no run had is not a column


class TestReading:

    def test_files_in_order_and_blank_lines(self, tmp_path):
        (tmp_path / 'a.jsonl').write_text(json.dumps(ROWS[0]) + '\n\n' + json.dumps(ROWS[5]) + '\n')
        (tmp_path / 'b.jsonl').write_text(json.dumps(ROWS[2]) + '\n')
        _rows = tables.read([str(tmp_path / 'a.jsonl'), str(tmp_path / 'b.jsonl')])
        assert [(_r['config'], _r['task']) for _r in _rows] == [('A', 't1'), ('B', 't1'), ('A', 't2')]

    @pytest.mark.parametrize('text, error', [('{"task": 1\n', r'a.jsonl:1: not a JSON line'),
                                             ('{"x": 1}\n', r'a.jsonl:1: not a record'),
                                             ('\n', 'no records in')])
    def test_what_it_refuses(self, tmp_path, text, error):
        (tmp_path / 'a.jsonl').write_text(text)
        with pytest.raises(ValueError, match=error):
            tables.read([str(tmp_path / 'a.jsonl')])


class TestRecordsCarryTheMutation:

    def test_the_mutation_counts(self):
        from ipandora.core.eval.records import _mutation
        assert _mutation([{'claim': 'kills mutants of the fixed functions', 'expr': '3/4 个变异被杀死'}]) == {
            'killed': 3, 'tested': 4}
        assert _mutation([{'claim': 'fail to pass', 'expr': '1/2 x'}]) is None and _mutation([]) is None


def grade(task, result):
    return [Check(name='答对', ok=result.output == 'right', expr='', src='output', claim='right')]


class TestEndToEnd:

    def test_from_runs_to_tables(self, tmp_path):
        _data = Dataset('d', tasks=[Task(id='t{}'.format(_i), input='q') for _i in range(4)])
        _lines = []
        for _name, _agent in (('good', lambda t: 'right'), ('bad', lambda t: 'right' if t.id == 't0' else 'wrong')):
            _run = evaluate(_data, _agent, grade, trials=2, check_references=False, manifest={'harness': _name})
            _lines += [json.dumps(_r, ensure_ascii=False, default=str) for _r in records.records(_run)]
        (tmp_path / 'r.jsonl').write_text('\n'.join(_lines) + '\n')
        _done = subprocess.run([sys.executable, '-m', 'ipandora.run', 'eval', 'table', str(tmp_path / 'r.jsonl')],
                               capture_output=True, text=True, timeout=120)
        assert _done.returncode == 0, _done.stderr
        assert '| good | — | 4 | 8 | 100.0% |' in _done.stdout and '| bad | — | 4 | 8 | 25.0% |' in _done.stdout
        assert 'good → bad' in _done.stdout and '刷绿指标' not in _done.stdout
        _json = subprocess.run([sys.executable, '-m', 'ipandora.run', 'eval', 'table', str(tmp_path / 'r.jsonl'),
                                '--json', '-o', str(tmp_path / 't.json')], capture_output=True, text=True, timeout=120)
        assert _json.returncode == 0 and '2 个配置' in _json.stdout
        _saved = json.loads((tmp_path / 't.json').read_text())
        assert [_r['success_rate'] for _r in _saved['main']] == [1.0, 0.25]

    def test_bad_input_exits_two(self, tmp_path):
        (tmp_path / 'r.jsonl').write_text('nope\n')
        _done = subprocess.run([sys.executable, '-m', 'ipandora.run', 'eval', 'table', str(tmp_path / 'r.jsonl')],
                               capture_output=True, text=True, timeout=120)
        assert _done.returncode == 2 and 'not a JSON line' in _done.stderr
