#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Gate: the documentation says what the code is.

Usage: check_docs.py            # check: links resolve, reference is current
       check_docs.py --write    # regenerate docs/reference/ from the code

Two checks:

1. **Every relative link and image in every tracked Markdown file resolves.**
   The docs are read on GitHub and by agents straight from the repository; a
   link to a file that moved is a dead end for both.
2. **docs/reference/ is generated, and current.** The CLI reference comes from
   the argparse definitions, the configuration reference from
   src/ipandora/conf/config.yaml and its comments. Written by hand they drift
   the first time an option changes; generated and checked, they cannot.

The third documentation gate -- the guide's code examples actually run -- is a
test, test/testdocs, because it needs the framework installed.
"""
import argparse
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFERENCE = os.path.join(REPO, 'docs', 'reference')
CONFIG = os.path.join(REPO, 'src', 'ipandora', 'conf', 'config.yaml')

_LINK = re.compile(r'!?\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)')
_FENCE = re.compile(r'^\s*(```|~~~)')
_HEADER = ('<!-- Generated by scripts/check_docs.py --write from {}. '
           'Do not edit by hand; edit the source and regenerate. -->\n\n')


def tracked_markdown():
    _out = subprocess.run(['git', '-c', 'core.quotepath=false', 'ls-files', '-z', '--cached',
                           '--others', '--exclude-standard', '*.md'],
                          cwd=REPO, capture_output=True, check=True).stdout
    return [_p for _p in _out.decode('utf-8').split('\0')
            if _p and not _p.startswith(('build/', '.venv/', 'src/ipandora/templates/'))]


def links(text: str):
    """Relative link targets outside code blocks, with their line numbers."""
    _in_code = False
    for _n, _line in enumerate(text.splitlines(), 1):
        if _FENCE.match(_line):
            _in_code = not _in_code
            continue
        if _in_code:
            continue
        for _m in _LINK.finditer(re.sub(r'`[^`]*`', '', _line)):
            _target = _m.group(1)
            if re.match(r'^[a-z][a-z0-9+.-]*:', _target, re.I) or _target.startswith('#'):
                continue
            yield _n, _target


def check_links():
    _problems = []
    for _rel in tracked_markdown():
        _path = os.path.join(REPO, _rel)
        with open(_path, encoding='utf-8') as _f:
            _text = _f.read()
        for _n, _target in links(_text):
            _file = _target.split('#', 1)[0]
            if not _file:
                continue
            _resolved = os.path.normpath(os.path.join(os.path.dirname(_path), _file))
            if not os.path.exists(_resolved):
                _problems.append('{}:{}: broken link {}'.format(_rel, _n, _target))
    return _problems


# -- generated reference -----------------------------------------------------------

def cli_reference() -> str:
    sys.path.insert(0, os.path.join(REPO, 'src'))
    from ipandora.run.commandmanager import CommandManager
    _manager = CommandManager()
    _sub = next(_a for _a in _manager.ap._actions if isinstance(_a, argparse._SubParsersAction))
    _out = [_HEADER.format('the argparse definitions in src/ipandora/run/commands/'),
            '# 命令行参考\n',
            '`ipandora <子命令> [参数]`。每个子命令也可以用 `-h` 查看同样的内容。\n']
    for _name in sorted(_sub.choices):
        _parser = _sub.choices[_name]
        _help = next((_c.help for _c in _sub._choices_actions if _c.dest == _name), '')
        _out += ['## `ipandora {}`\n'.format(_name), '{}\n'.format(_help or '')]
        _rows = []
        for _action in _parser._actions:
            if isinstance(_action, argparse._HelpAction):
                continue
            if _action.option_strings:
                _flags = ', '.join('`{}`'.format(_o) for _o in _action.option_strings)
                if _action.nargs != 0:
                    _flags += ' `{}`'.format(_action.metavar or _action.dest.upper())
            else:
                _flags = '`{}`'.format(_action.metavar or _action.dest)
            _default = _action.default
            _shown = '' if _default in (None, False, [], argparse.SUPPRESS) else '`{}`'.format(_default)
            _rows.append('| {} | {} | {} |'.format(
                _flags, _shown, ' '.join((_action.help or '').split()).replace('|', '\\|')))
        if _rows:
            _out += ['| 参数 | 默认值 | 说明 |', '|---|---|---|'] + _rows + ['']
    return '\n'.join(_out).rstrip() + '\n'


def config_reference() -> str:
    """Every key in config.yaml, its default, and the comment above or beside it."""
    _out = [_HEADER.format('src/ipandora/conf/config.yaml'), '# 配置参考\n',
            '框架的默认配置。用例项目在 `conf/config.yaml` 里只写要改的键，按环境叠加写在 '
            '`conf/<env>.yaml`（`ipandora run -e <env>`），见 [配置、环境与测试数据](../guide/config.md)。\n']
    with open(CONFIG, encoding='utf-8') as _f:
        _lines = _f.read().splitlines()
    _entries = []      # (indent, key, value, note)
    _notes = []
    for _i, _line in enumerate(_lines):
        _stripped = _line.strip()
        if not _stripped:
            _notes = []
            continue
        if _stripped.startswith('#'):
            _text = _stripped.lstrip('#').strip()
            if _text:
                _notes.append(_text)
            continue
        _m = re.match(r'^(\s*)([A-Za-z_][\w-]*):\s*(.*?)\s*$', _line)
        if not _m:
            continue
        _rest = _m.group(3)
        _value, _, _inline = ('', '', _rest[1:]) if _rest.startswith('#') else _rest.partition(' #')
        _entries.append((len(_m.group(1)), _m.group(2), _value.strip(),
                         ' '.join(_notes + ([_inline.strip()] if _inline.strip() else [])), _i))
        _notes = []
    _rows, _sections, _stack = [], {}, []
    for _n, (_indent, _key, _value, _note, _i) in enumerate(_entries):
        while _stack and _stack[-1][0] >= _indent:
            _stack.pop()
        _path = '.'.join([_k for _, _k in _stack] + [_key])
        _next = _entries[_n + 1] if _n + 1 < len(_entries) else None
        if not _value and _next and _next[0] > _indent:
            if not _stack:
                _sections[_key] = _note
            _stack.append((_indent, _key))
            continue
        _rows.append((_path.split('.')[0], _path, _value or 'null', _note))
    for _top in _sections:
        _out.append('## `{}`\n'.format(_top))
        if _sections[_top]:
            _out.append('{}\n'.format(_sections[_top]))
        _mine = [_r for _r in _rows if _r[0] == _top]
        if _mine:
            _out += ['| 键 | 默认值 | 说明 |', '|---|---|---|']
            _out += ['| `{}` | `{}` | {} |'.format(_p, _v, _n.replace('|', '\\|'))
                     for _, _p, _v, _n in _mine]
            _out.append('')
    return '\n'.join(_out).rstrip() + '\n'


GENERATED = {'cli.md': cli_reference, 'config.md': config_reference}


def check_reference(write: bool):
    _problems = []
    os.makedirs(REFERENCE, exist_ok=True)
    for _name, _make in GENERATED.items():
        _path = os.path.join(REFERENCE, _name)
        _want = _make()
        _have = open(_path, encoding='utf-8').read() if os.path.exists(_path) else None
        if _have == _want:
            continue
        if write:
            with open(_path, 'w', encoding='utf-8') as _f:
                _f.write(_want)
            print('wrote docs/reference/{}'.format(_name))
        else:
            _problems.append('docs/reference/{} is out of date: python scripts/check_docs.py '
                             '--write'.format(_name))
    return _problems


def main(argv) -> int:
    _write = '--write' in argv
    _problems = check_reference(_write) + check_links()
    for _p in _problems:
        print('  ' + _p, file=sys.stderr)
    if _problems:
        return 1
    print('OK: every relative link resolves; docs/reference/ matches the code')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
